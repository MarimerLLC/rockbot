#!/usr/bin/env bash
# Connects RockBot to one Slack workspace, read-only, through the slack-mcp container. Run it once
# per workspace; safe to re-run.
#   - prints a link that creates the "RockBot" Slack app from deploy/slack/manifest.json
#   - checks the user token you paste with auth.test
#   - stores SLACK_<NAME>_TOKEN / SLACK_<NAME>_TEAM_ID and SLACK_WORKSPACES in deploy/docker-compose/.env
#   - regenerates deploy/docker-compose/slack.env, starts slack-mcp and registers "slack"
#
# Usage: setup.sh --workspace NAME [--no-dms] [--new-token]
#        setup.sh --render-only      (regenerate slack.env from .env and restart, e.g. after chezmoi apply)
#   NAME is what RockBot calls the workspace, e.g. work or acme: lower-case letters, digits and '-'.
#   --no-dms     create the app without DM and group-DM scopes
#   --new-token  ask for a new token even if one is stored
set -euo pipefail
# shellcheck source=../lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"
SLACK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SLACK_ENV="$COMPOSE_DIR/slack.env"

workspace=""
no_dms=false
new_token=false
render_only=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --workspace) workspace="$2"; shift 2 ;;
    --no-dms) no_dms=true; shift ;;
    --new-token) new_token=true; shift ;;
    --render-only) render_only=true; shift ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done

require curl jq docker

# Prefix of a workspace's keys in .env: work -> SLACK_WORK_, acme-eu -> SLACK_ACME_EU_.
key_prefix() { printf 'SLACK_%s_' "$(tr 'a-z-' 'A-Z_' <<<"$1")"; }

# Writes slack.env: indexed .NET config that points at the secrets in .env, never copies them.
render_env() {
  local names i=0 name prefix
  names="$(env_get SLACK_WORKSPACES)"
  {
    echo "# Generated by deploy/slack/setup.sh from SLACK_WORKSPACES in .env. Holds no secrets; don't edit."
    IFS=',' read -r -a list <<<"$names"
    for name in "${list[@]}"; do
      [[ -n "$name" ]] || continue
      prefix="$(key_prefix "$name")"
      echo "Slack__Workspaces__${i}__Name=$name"
      echo "Slack__Workspaces__${i}__Token=\${${prefix}TOKEN}"
      echo "Slack__Workspaces__${i}__TeamId=\${${prefix}TEAM_ID:-}"
      i=$((i + 1))
    done
  } > "$SLACK_ENV"
  log "Wrote $SLACK_ENV ($i workspace(s))"
}

start_and_register() {
  enable_profile slack
  log "Building and starting slack-mcp"
  "${COMPOSE[@]}" up -d --build slack-mcp
  register_mcp_server slack '{"type":"sse","url":"http://slack-mcp:8080/"}'
}

if $render_only; then
  [[ -n "$(env_get SLACK_WORKSPACES)" ]] || die "SLACK_WORKSPACES is not set in $ENV_FILE; run setup.sh --workspace NAME first"
  render_env
  start_and_register
  exit 0
fi

[[ -n "$workspace" ]] || die "pass --workspace NAME, e.g. --workspace work"
# Accept a display name like "Spinn Pty Ltd" and turn it into the short label the tools use.
slug="$(tr '[:upper:]' '[:lower:]' <<<"$workspace" | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//' | cut -c1-32 | sed -E 's/-+$//')"
[[ "$slug" =~ ^[a-z0-9][a-z0-9-]{0,31}$ ]] || die "can't make a workspace name from '$workspace'; use letters, digits and '-'"
[[ "$slug" == "$workspace" ]] || log "Using '$slug' as the workspace name for '$workspace'"
workspace="$slug"
prefix="$(key_prefix "$workspace")"

token="${SLACK_TOKEN:-}"
$new_token || token="${token:-$(env_get "${prefix}TOKEN")}"

if [[ -z "$token" ]]; then
  manifest="$(jq -c --argjson nodms "$no_dms" \
    'if $nodms then .oauth_config.scopes.user |= map(select(startswith("im:") or startswith("mpim:") | not)) else . end' \
    "$SLACK_DIR/manifest.json")"
  log "1. Open this link, pick the '$workspace' workspace, and create the app:"
  log "     https://api.slack.com/apps?new_app=1&manifest_json=$(jq -rn --arg m "$manifest" '$m | @uri')"
  log "2. Under 'Install App', click 'Install to Workspace' and allow it."
  log "   If the workspace needs approval, click 'Request to Install', wait for the admin, then come back here."
  log "3. Copy the 'User OAuth Token' (xoxp-...) from 'OAuth & Permissions'."
  token="$(read_secret SLACK_TOKEN "Paste the User OAuth Token for $workspace")"
fi
[[ "$token" == xoxp-* ]] || die "that isn't a user token; it should start with xoxp- (bot tokens, xoxb-, can't search)"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
chmod 700 "$work"
printf 'Authorization: Bearer %s\n' "$token" > "$work/auth.header"
curl -sS -D "$work/headers" -o "$work/auth.json" -H "@$work/auth.header" -X POST https://slack.com/api/auth.test
jq -e .ok "$work/auth.json" >/dev/null || die "Slack rejected the token: $(jq -r .error "$work/auth.json")"
team_id="$(jq -r .team_id "$work/auth.json")"
log "PASS: token is for $(jq -r .user "$work/auth.json") in $(jq -r .team "$work/auth.json") ($team_id)"

scopes="$(tr -d '\r' < "$work/headers" | awk -F': ' 'tolower($1) == "x-oauth-scopes" { print $2 }')"
for scope in channels:history search:read users:read; do
  [[ ",${scopes// /}," == *",$scope,"* ]] || warn "the token lacks $scope; recreate the app from the manifest link above (--new-token)"
done
if [[ ",${scopes// /}," == *",chat:write,"* ]]; then
  warn "this token can post messages (chat:write). RockBot's server has no posting tools, but a read-only app is safer."
fi

upsert_env "${prefix}TOKEN" "$token"
upsert_env "${prefix}TEAM_ID" "$team_id"
unset token
names="$(env_get SLACK_WORKSPACES)"
[[ ",$names," == *",$workspace,"* ]] || upsert_env SLACK_WORKSPACES "${names:+$names,}$workspace"
log "Stored ${prefix}TOKEN, ${prefix}TEAM_ID and SLACK_WORKSPACES in $ENV_FILE"

render_env
start_and_register
