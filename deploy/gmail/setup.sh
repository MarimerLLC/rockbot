#!/usr/bin/env bash
# Connects RockBot to one Gmail account (read, search and drafts; never send) through the
# gmail-mcp container. Run it once per account; safe to re-run.
#   - stores the Google Cloud OAuth client (GMAIL_CLIENT_ID / GMAIL_CLIENT_SECRET) the first time
#   - opens Google's consent page for the account and catches the answer on 127.0.0.1
#   - stores GMAIL_<NAME>_EMAIL / GMAIL_<NAME>_REFRESH_TOKEN and GMAIL_ACCOUNTS in deploy/docker-compose/.env
#   - regenerates deploy/docker-compose/gmail.env, starts gmail-mcp and registers "gmail"
#
# Usage: setup.sh --account NAME [--email ADDRESS] [--reconsent]
#        setup.sh --render-only      (regenerate gmail.env from .env and restart, e.g. after chezmoi apply)
#   NAME is what RockBot calls the account, e.g. personal or work: lower-case letters, digits and '-'.
#   --email      the address you expect, pre-filled on Google's sign-in page and checked afterwards
#   --reconsent  sign in again even if a refresh token is stored
# The client id and secret are read from GMAIL_CLIENT_ID / GMAIL_CLIENT_SECRET, .env, or prompted for.
set -euo pipefail
# shellcheck source=../lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"
GMAIL_ENV="$COMPOSE_DIR/gmail.env"
SCOPES="https://www.googleapis.com/auth/gmail.readonly https://www.googleapis.com/auth/gmail.compose"

account=""
email=""
reconsent=false
render_only=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --account) account="$2"; shift 2 ;;
    --email) email="$2"; shift 2 ;;
    --reconsent) reconsent=true; shift ;;
    --render-only) render_only=true; shift ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done

require curl jq docker openssl python3

# Prefix of an account's keys in .env: personal -> GMAIL_PERSONAL_, work-au -> GMAIL_WORK_AU_.
key_prefix() { printf 'GMAIL_%s_' "$(tr 'a-z-' 'A-Z_' <<<"$1")"; }

# Writes gmail.env: indexed .NET config that points at the secrets in .env, never copies them.
render_env() {
  local i=0 name prefix
  {
    echo "# Generated by deploy/gmail/setup.sh from GMAIL_ACCOUNTS in .env. Holds no secrets; don't edit."
    IFS=',' read -r -a list <<<"$(env_get GMAIL_ACCOUNTS)"
    for name in "${list[@]}"; do
      [[ -n "$name" ]] || continue
      prefix="$(key_prefix "$name")"
      echo "Gmail__Accounts__${i}__Name=$name"
      echo "Gmail__Accounts__${i}__Email=\${${prefix}EMAIL}"
      echo "Gmail__Accounts__${i}__RefreshToken=\${${prefix}REFRESH_TOKEN}"
      i=$((i + 1))
    done
  } > "$GMAIL_ENV"
  log "Wrote $GMAIL_ENV ($i account(s))"
}

start_and_register() {
  enable_profile gmail
  log "Building and starting gmail-mcp"
  "${COMPOSE[@]}" up -d --build gmail-mcp
  # get_attachment returns binary files as base64 in "content"; the bridge saves them to the shared
  # volume and gives the model a path. No mimeField: the type comes from the file name.
  register_mcp_server gmail '{"type":"sse","url":"http://gmail-mcp:8080/",
    "attachments":{"capture":{"rules":[{"tools":["get_attachment"],"contentField":"content","nameField":"name"}]}}}'
}

if $render_only; then
  [[ -n "$(env_get GMAIL_ACCOUNTS)" ]] || die "GMAIL_ACCOUNTS is not set in $ENV_FILE; run setup.sh --account NAME first"
  render_env
  start_and_register
  exit 0
fi

[[ "$account" =~ ^[a-z0-9][a-z0-9-]{0,31}$ ]] || die "pass --account NAME: lower-case letters, digits and '-', e.g. --account personal"
prefix="$(key_prefix "$account")"

client_id="${GMAIL_CLIENT_ID:-$(env_get GMAIL_CLIENT_ID)}"
client_secret="${GMAIL_CLIENT_SECRET:-$(env_get GMAIL_CLIENT_SECRET)}"
if [[ -z "$client_id" || -z "$client_secret" ]]; then
  log "No Google OAuth client stored yet. Create one as described in deploy/gmail/README.md (section 1):"
  log "  a Desktop app client, Gmail API enabled, consent screen published 'In production'."
  [[ -t 0 ]] || die "GMAIL_CLIENT_ID / GMAIL_CLIENT_SECRET are not set and there is no terminal to prompt on"
  read -r -p "Client ID (…apps.googleusercontent.com): " client_id
  client_secret="$(read_secret GMAIL_CLIENT_SECRET "Client secret")"
fi
[[ "$client_id" == *.apps.googleusercontent.com ]] || die "that doesn't look like a Google OAuth client id"

if ! $reconsent && [[ -n "$(env_get "${prefix}REFRESH_TOKEN")" ]]; then
  log "Account '$account' is already connected ($(env_get "${prefix}EMAIL")); use --reconsent to sign in again"
else
  work="$(mktemp -d)"
  trap 'kill "${listener:-}" 2>/dev/null || true; rm -rf "$work"' EXIT
  chmod 700 "$work"

  # PKCE and state, per RFC 7636 / RFC 6749.
  verifier="$(openssl rand -base64 64 | tr -d '\n=+/' | cut -c1-64)"
  challenge="$(printf '%s' "$verifier" | openssl dgst -sha256 -binary | openssl base64 | tr '+/' '-_' | tr -d '=\n')"
  state="$(openssl rand -hex 16)"

  # One-shot listener on a free loopback port: writes the redirect's query to $work/answer.json.
  python3 -I -c '
import http.server, json, sys, time, urllib.parse
out, port_file = sys.argv[1], sys.argv[2]
done = False
class Handler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        global done
        query = {k: v[0] for k, v in urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query).items()}
        if "code" not in query and "error" not in query:
            self.send_response(404); self.end_headers(); return
        with open(out, "w") as f: json.dump(query, f)
        self.send_response(200); self.send_header("Content-Type", "text/html; charset=utf-8"); self.end_headers()
        self.wfile.write("<p>RockBot: done. You can close this tab and go back to the terminal.</p>".encode())
        done = True
    def log_message(self, *args): pass
server = http.server.HTTPServer(("127.0.0.1", 0), Handler)
server.timeout = 5
with open(port_file, "w") as f: f.write(str(server.server_address[1]))
deadline = time.time() + 600
while not done and time.time() < deadline: server.handle_request()
' "$work/answer.json" "$work/port" &
  listener=$!
  for _ in $(seq 50); do [[ -s "$work/port" ]] && break; sleep 0.1; done
  [[ -s "$work/port" ]] || die "could not start the local listener"
  redirect="http://127.0.0.1:$(cat "$work/port")"

  url="https://accounts.google.com/o/oauth2/v2/auth?$(jq -rn \
    --arg client_id "$client_id" --arg redirect "$redirect" --arg scope "$SCOPES" \
    --arg challenge "$challenge" --arg state "$state" --arg hint "$email" '
    {client_id: $client_id, redirect_uri: $redirect, response_type: "code", scope: $scope,
     access_type: "offline", prompt: "consent", code_challenge: $challenge, code_challenge_method: "S256",
     state: $state} + (if $hint == "" then {} else {login_hint: $hint} end)
    | to_entries | map("\(.key)=\(.value | @uri)") | join("&")')"

  log "Open this link in a browser on this machine and sign in to the '$account' account${email:+ ($email)}:"
  log "  $url"
  log "Google may warn that the app isn't verified: choose Advanced > Go to … (unsafe) — it's your own client."
  command -v xdg-open >/dev/null && xdg-open "$url" >/dev/null 2>&1 || true
  log "Waiting for Google's answer (10 minutes)..."
  wait "$listener" || true
  [[ -s "$work/answer.json" ]] || die "no answer from Google; run the script again"
  [[ "$(jq -r '.state // ""' "$work/answer.json")" == "$state" ]] || die "the answer's state didn't match; run the script again"
  if [[ "$(jq -r '.error // ""' "$work/answer.json")" != "" ]]; then
    err="$(jq -r .error "$work/answer.json")"
    [[ "$err" == "access_denied" ]] && die "consent was denied. For a Workspace account, its admin may block unverified apps; see README section 3."
    die "Google returned an error: $err"
  fi
  granted="$(jq -r '.scope // ""' "$work/answer.json")"
  [[ "$granted" == *gmail.readonly* && "$granted" == *gmail.compose* ]] \
    || die "both Gmail permissions are needed, but Google granted only: ${granted:-none}. Re-run and tick both boxes."

  # Exchange the code. Secrets go through files, not argv.
  jq -rn --arg code "$(jq -r .code "$work/answer.json")" --arg id "$client_id" --arg secret "$client_secret" \
    --arg redirect "$redirect" --arg verifier "$verifier" '
    {code: $code, client_id: $id, client_secret: $secret, redirect_uri: $redirect, code_verifier: $verifier,
     grant_type: "authorization_code"} | to_entries | map("\(.key)=\(.value | @uri)") | join("&")' > "$work/exchange"
  curl -sS -o "$work/tokens.json" -d "@$work/exchange" https://oauth2.googleapis.com/token
  refresh="$(jq -r '.refresh_token // ""' "$work/tokens.json")"
  [[ -n "$refresh" ]] || die "Google returned no refresh token: $(jq -r '.error_description // .error // "unknown error"' "$work/tokens.json")"

  printf 'Authorization: Bearer %s\n' "$(jq -r .access_token "$work/tokens.json")" > "$work/auth.header"
  curl -sS -o "$work/profile.json" -H "@$work/auth.header" https://gmail.googleapis.com/gmail/v1/users/me/profile
  address="$(jq -r '.emailAddress // ""' "$work/profile.json")"
  [[ -n "$address" ]] || die "could not read the Gmail profile: $(head -c 300 "$work/profile.json")"
  if [[ -n "$email" && "${address,,}" != "${email,,}" ]]; then
    die "you signed in as $address, not $email; run again and pick the right account"
  fi
  log "PASS: signed in as $address ($(jq -r .messagesTotal "$work/profile.json") messages)"

  upsert_env "${prefix}EMAIL" "$address"
  upsert_env "${prefix}REFRESH_TOKEN" "$refresh"
  unset refresh
fi

upsert_env GMAIL_CLIENT_ID "$client_id"
upsert_env GMAIL_CLIENT_SECRET "$client_secret"
unset client_secret
names="$(env_get GMAIL_ACCOUNTS)"
[[ ",$names," == *",$account,"* ]] || upsert_env GMAIL_ACCOUNTS "${names:+$names,}$account"
log "Stored GMAIL_CLIENT_*, ${prefix}EMAIL, ${prefix}REFRESH_TOKEN and GMAIL_ACCOUNTS in $ENV_FILE"

render_env
start_and_register
